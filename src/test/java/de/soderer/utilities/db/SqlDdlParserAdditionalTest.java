	@Test
	public void testCommentOn() throws Exception {
		final DbStructure structure = parse("CREATE SCHEMA app;\n"
				+ "CREATE TABLE app.t (id INT, name VARCHAR(10));\n"
				+ "CREATE TABLE plain (id INT);\n"
				+ "COMMENT ON SCHEMA app IS 'Application';\n"
				+ "COMMENT ON SCHEMA missing IS 'x';\n"
				+ "COMMENT ON TABLE app.t IS 'It''s a table';\n"
				+ "COMMENT ON TABLE plain IS 'Plain';\n"
				+ "COMMENT ON TABLE plain IS NULL;\n"
				+ "COMMENT ON TABLE missing.t IS 'x';\n"
				+ "COMMENT ON TABLE app.missing IS 'x';\n"
				+ "COMMENT ON COLUMN app.t.name IS 'Name column';\n"
				+ "COMMENT ON COLUMN plain.id IS 'Id';\n"
				+ "COMMENT ON COLUMN app.t.missing IS 'x';\n"
				+ "COMMENT ON COLUMN missing.t.c IS 'x';\n"
				+ "COMMENT ON COLUMN app.missing.c IS 'x';\n"
				+ "COMMENT ON INDEX ix IS 'ignored';");
		assertEquals("Application", structure.getSchemas().get("app").getSchemaComment());
		final DbTable table = table(structure, "app", "t");
		assertEquals("It's a table", table.getTableComment());
		assertEquals("Name column", table.getColumns().get("name").getColumnComment());
		final DbTable plain = table(structure, "", "plain");
		assertNull(plain.getTableComment());
		assertEquals("Id", plain.getColumns().get("id").getColumnComment());
	}

	@Test
	public void testCommentsAndStatementSplitting() throws Exception {
		final DbStructure structure = parse("-- leading comment; CREATE TABLE ignored (x INT);\n"
				+ "/* block comment\n with ; and CREATE TABLE ignored2 (x INT) */\n"
				+ "CREATE TABLE t (\n"
				+ "  a VARCHAR(10) DEFAULT '-- not a comment',\n"
				+ "  b VARCHAR(10) DEFAULT '/* no block */',\n"
				+ "  c VARCHAR(10) DEFAULT 'semi;colon' -- trailing comment\n"
				+ ");;\n"
				+ "CREATE TABLE u (id INT)\n"
				+ "/* unterminated block comment");
		final DbTable table = table(structure, "", "t");
		assertEquals("-- not a comment", type(table, "a").getDefaultValue());
		assertEquals("/* no block */", type(table, "b").getDefaultValue());
		assertEquals("semi;colon", type(table, "c").getDefaultValue());
		assertNotNull(table(structure, "", "u"));
		assertEquals(2, structure.getSchemas().get("").getTables().size());
		assertNotNull(new SqlDdlParser());
	}
